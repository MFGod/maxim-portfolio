/**
 * Профиль бумаги в раскрытой книге: как высоко лежит страница на расстоянии
 * `fromSpine` от корешка.
 *
 * Отдельным модулем, потому что потребителей двое — лежащие страницы половин и
 * листающийся лист, — а разъехаться им нельзя. Лист садится на стопку, и если
 * его форма не совпадёт с формой лежащей страницы, в момент подмены разворота
 * бумага провалится разом: конец переворота отдаёт рывком. Это уже случалось.
 *
 * Форма взята с настоящей раскрытой книги: у корешка бумага круто уходит вниз
 * в жёлоб, дальше быстро выполаживается и к внешнему краю идёт почти ровно.
 * Квадрат даёт ровно такой ход — наибольший наклон у корешка, нулевой у края.
 */

/**
 * @param fromSpine доля пути от корешка к внешнему краю, от 0 до 1
 * @param lift высота бумаги у внешнего края
 * @param dip насколько ниже она у самого корешка
 */
export function pageProfile(fromSpine: number, lift: number, dip: number): number {
  const clamped = Math.min(Math.max(fromSpine, 0), 1);
  return lift - dip * (1 - clamped) ** 2;
}
