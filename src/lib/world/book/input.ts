/**
 * Что делает щелчок по книге.
 *
 * Правило вынесено из сборки по той же причине, что и раскладка граней в
 * `faces.ts`: его нельзя проверить ни типами, ни статичным кадром — ошибка
 * видна только тем, что книга не слушается, — а вариантов у него шесть.
 *
 * Само действие здесь не выполняется: файл знает про состояние книги и про то,
 * куда попал луч, и ничего не знает про `three`, анимации и переходы.
 */

/** Во что попал луч указателя. */
export type PickTarget = 'left' | 'right' | 'tab';

/** Состояние книги на момент щелчка. */
export type PickState = {
  opened: boolean;
  /** Индекс текущего разворота. */
  spread: number;
  /** Пришёлся ли щелчок на ссылку страницы. */
  link: boolean;
};

/** Что книге делать. */
export type PickAction = 'open' | 'close' | 'forward' | 'back' | 'guide' | 'link';

/**
 * Решает, что делает щелчок.
 *
 * У закрытой книги любое попадание раскрывает её — по тому же месту, куда
 * посетитель и целился, — кроме закладки: она ведёт на свой разворот и в
 * закрытом виде тоже, как заложенная лента в настоящей книге.
 *
 * У раскрытой половина решает направление, как в живой книге: тронул правую —
 * листаешь вперёд, левую — назад. На первом развороте листать назад некуда, и
 * щелчок по левой странице закрывает книгу: это единственное движение, которое
 * там осталось, и без него левая половина просто не отвечает.
 *
 * Ссылка старше листания и старше закрытия: она занимает одну строку из всей
 * полосы, и попасть в неё случайно нельзя, а вот промахнуться мимо неё, если
 * бы страница успевала перевернуться, — запросто.
 */
export function pickAction(state: PickState, target: PickTarget): PickAction {
  if (target === 'tab') return 'guide';
  if (!state.opened) return 'open';
  if (state.link) return 'link';
  if (target === 'right') return 'forward';

  return state.spread === 0 ? 'close' : 'back';
}
