/**
 * Кручение книги в руках: из протяжки указателя в поворот.
 *
 * Закрытый том лежит в углу кадра, и посетитель вправе повертеть его, чтобы
 * рассмотреть корешок и заднюю крышку. Правило чистое — из пикселей в кватернион.
 *
 * Оси берутся экранные, а не мировые, и это работает потому, что книга —
 * ребёнок камеры по матрице: её родительская система координат и есть система
 * камеры. Протяжка вправо уводит переднюю крышку вправо, протяжка вниз
 * наклоняет верх книги к зрителю — так же, как повернулся бы предмет в руке.
 */

import * as THREE from 'three';

/**
 * Сколько пикселей протяжки даёт полный оборот.
 *
 * Шестьсот — это примерно ширина книги в кадре, взятая четырежды: оборот
 * выходит за движение через треть экрана, и рассмотреть все четыре стороны
 * можно одним махом, не отпуская кнопку.
 */
export const SPIN_TURN_PIXELS = 600;

/** Вертикаль экрана: вокруг неё книга вертится при протяжке вбок. */
const SCREEN_UP = new THREE.Vector3(0, 1, 0);

/** Горизонталь экрана: вокруг неё книга кувыркается при протяжке вверх-вниз. */
const SCREEN_RIGHT = new THREE.Vector3(1, 0, 0);

const RADIANS_PER_PIXEL = (Math.PI * 2) / SPIN_TURN_PIXELS;

/**
 * Поворот за один шаг протяжки.
 *
 * Складывается из рыскания и кувырка: сперва поворот вокруг вертикали, следом
 * вокруг горизонтали. Порядок на шаг в несколько пикселей роли не играет — на
 * малых углах повороты почти коммутируют, — но зафиксирован, чтобы кручение
 * не зависело от частоты событий указателя.
 *
 * @param dx сдвиг указателя вправо, в пикселях
 * @param dy сдвиг указателя вниз, в пикселях
 */
export function spinStep(dx: number, dy: number): THREE.Quaternion {
  const yaw = new THREE.Quaternion().setFromAxisAngle(
    SCREEN_UP,
    dx * RADIANS_PER_PIXEL,
  );
  const tumble = new THREE.Quaternion().setFromAxisAngle(
    SCREEN_RIGHT,
    dy * RADIANS_PER_PIXEL,
  );

  return tumble.multiply(yaw);
}

/**
 * Сколько от накрученного поворота осталось, пока книга распрямляется.
 *
 * При раскрытии книга едет в позу чтения и по дороге разворачивается к
 * зрителю: читать боком нельзя. Доля идёт от единицы (как оставили) к нулю
 * (смотрит прямо).
 */
export function unwound(from: THREE.Quaternion, share: number): THREE.Quaternion {
  const settled = Math.min(Math.max(share, 0), 1);
  return new THREE.Quaternion().slerpQuaternions(new THREE.Quaternion(), from, settled);
}
