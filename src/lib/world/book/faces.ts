/**
 * Какой разворот попадает на какую видимую грань книги.
 *
 * Граней четыре: лежащие страницы обеих половин и две стороны листающегося
 * листа. Правило чистое — из состояния книги в индексы разворотов, — и вынесено
 * из сборки именно поэтому: ошибку в нём не видно ни типам, ни на статичном
 * кадре, а стоит она чужим текстом на странице. Ловили её несколько раз.
 *
 * Сторону страницы (левую или правую) грань выбирает не сама: у каждой грани
 * она своя и неизменна, и записана здесь в типе.
 */

/** Состояние книги, от которого зависит раскладка. */
export type FacesState = {
  /** Индекс текущего разворота. */
  spread: number;
  turning: boolean;
  /** Куда идёт переворот: вперёд или назад. */
  direction: 1 | -1;
};

/** Индексы разворотов по граням. У листа — `null`, пока он не в перевороте. */
export type BookFaces = {
  /** Разворот, чья **левая** страница лежит на левой половине. */
  left: number;
  /** Разворот, чья **правая** страница лежит на правой половине. */
  right: number;
  /** Разворот, чья **правая** страница уехала на лицо листа. */
  sheetFront: number | null;
  /** Разворот, чья **левая** страница пришла на изнанку листа. */
  sheetBack: number | null;
};

/**
 * Раскладывает развороты по граням.
 *
 * Вне переворота видны две страницы одного разворота, лист скрыт. В перевороте
 * лист лежит между разворотами `base` и `base + 1`, каким бы ни было
 * направление: вперёд он уходит с текущего разворота, назад — приходит на
 * предыдущий. Одна формула вместо двух ветвей.
 *
 * За края книги здесь не смотрят: переворот наружу не запускается вовсе, а
 * зажим индексов — дело того, кто берёт текстуру.
 */
export function spreadFaces({ spread, turning, direction }: FacesState): BookFaces {
  if (!turning) {
    return { left: spread, right: spread, sheetFront: null, sheetBack: null };
  }

  const base = direction === -1 ? spread - 1 : spread;
  return { left: base, right: base + 1, sheetFront: base, sheetBack: base + 1 };
}
