/**
 * Размеры, позы, длительности и цвета книги — всё, что подбирается.
 *
 * Собрано в одном файле намеренно: за время работы каждое из этих чисел
 * менялось по нескольку раз, и держать их вперемешку со сборкой сцены значило
 * искать по всему модулю. Почти у каждого в комментарии стоит, из чего оно
 * получено, — эти обоснования дороже самих значений.
 */

import * as THREE from 'three';

/** Ширина страницы от корешка к внешнему краю, в юнитах мира. */
export const PAGE_W = 0.2;
export const PAGE_H = 0.28;

/**
 * Толщина переплёта и бумажного блока одной половины.
 *
 * При 0.006 и 0.014 против ширины страницы 0.2 книга читалась двумя листами
 * на подложке, а не книгой. Сейчас раскрытая книга в поперечнике 0.068 —
 * примерно треть страницы, как у толстого тома.
 */
export const BOARD_T = 0.008;
export const BLOCK_T = 0.026;

/**
 * Зазоры по глубине. Каждый слой книги обязан стоять строго выше предыдущего.
 *
 * Без них страница лежала ровно на верхней грани бумажного блока — обе в
 * `z = 0`, — и глубинный буфер не мог решить, что впереди: страница шла
 * коричневыми полосами переплёта. Точность буфера на этой дистанции около
 * 1e-7 юнита, так что десятых долей миллиметра хватает с запасом в тысячи раз.
 */
export const PAGE_LIFT = 0.0006;

/**
 * Насколько бумага проваливается в жёлоб у корешка.
 *
 * Страница кладётся на `PAGE_LIFT + GUTTER_DIP` и проваливается вниз ровно на
 * `GUTTER_DIP`, так что у корешка она садится на `PAGE_LIFT` — то есть всё
 * ещё выше верхней грани блока. Если провал отсчитывать от `PAGE_LIFT`, бумага
 * уходит ниже блока на две трети ширины, и стопка съедает текст.
 */
export const GUTTER_DIP = 0.016;

/**
 * Насколько поднята к зрителю каждая половина раскрытой книги, в радианах.
 *
 * Раскрытая книга не лежит плашмя: переплёт держит половины пологой дугой, и
 * именно этот наклон отличает книгу от двух листов на подложке. Семь градусов
 * — столько даёт настоящий том средней толщины.
 */
export const OPEN_TILT = 0.12;

/**
 * Ширина жёлоба по корешку: на неё расступаются стопки и бумага.
 *
 * 2.5 % ширины страницы. Двенадцать тысячных читались не швом, а щелью между
 * двумя отдельными книжками.
 */
export const SEAM_WIDTH = 0.005;

/**
 * Отступ бумаги от корешка: половина жёлоба.
 *
 * Одинаков у лежащих страниц, у торцов блока и у листающегося листа — иначе
 * бумага накрывает шов сверху, и в конце переворота полоска у корешка разом
 * меняется с бумаги на тёмное дно жёлоба.
 */
export const PAGE_INSET = SEAM_WIDTH / 2;

/**
 * Просвет листающегося листа над лежащей бумагой.
 *
 * Величина покрывает самый глубокий провал листа под страницу. У корешка
 * подъём от поворота равен нулю, а профиль листа к середине переворота почти
 * распрямлён — тогда как лежащая страница остаётся провалённой в жёлоб на всю
 * глубину. На доле 0.4 лист уходил под страницу на всём отрезке до `x = 0.007`
 * от корешка, и оттуда сквозь него торчал чужой текст. Наибольший недобор —
 * высота страницы у корешка, 0.0010; полторы тысячных перекрывают с запасом.
 */
export const SHEET_CLEARANCE = 0.0015;

/**
 * Насколько бумажный блок шире страницы.
 *
 * Вровень его торец полностью прячется под бумагой, и раскрытая книга читается
 * двумя листами на подложке.
 */
export const BLOCK_OVERSIZE = 1.012;

/** Насколько переплёт свисает за блок, как у настоящего тома. */
export const COVER_MARGIN = 0.014;

/** Насколько дно жёлоба утоплено ниже верхней грани блока. */
export const SEAM_DEPTH = 0.001;

/** Тень в жёлобе, куда не достаёт свет. */
export const SEAM_COLOR = '#241f18';

/** Нитки переплёта: единственное, что видно на дне жёлоба. */
export const THREAD_COLOR = '#8d7c62';

/** Высота бумаги у внешнего края. Общая для страниц и листающегося листа. */
export const PAPER_LIFT = PAGE_LIFT + GUTTER_DIP;

/**
 * Поза чтения.
 *
 * Дистанция считается, а не подбирается. Доля высоты кадра равна
 * H / (2·d·tan(32.5°)); при d = 0.35 книга высотой 0.29 давала 63 %, но с
 * наклоном её нижний край уходил в NDC за −1.1 — то есть за нижнюю кромку
 * кадра. При d = 0.44 книга занимает около 52 % высоты: текст читается, а
 * ближний нижний угол остаётся в кадре с запасом. Запас сторожит тест — он
 * проецирует все восемь углов габарита и требует не меньше 5 % от кромки.
 */
export const READING = {
  position: new THREE.Vector3(0, -0.05, -0.44),
  rotation: new THREE.Euler(-0.34, 0, 0),
};

/**
 * Запас между книгой в позе чтения и кромкой кадра, в долях NDC.
 *
 * Живёт здесь, а не в тесте: это условие на позу, а не свойство проверки. Пять
 * процентов — примерно ширина мизинца на экране ноутбука; ближе книга начинает
 * читаться обрезанной, даже когда формально помещается.
 */
export const READING_MARGIN = 0.05;

/**
 * Торцы переплёта: кожа без золота.
 *
 * Снято с самой развёртки — средняя по кромке в двадцать пикселей с обоих
 * краёв, 5560 проб. Подбирать на глаз тут нечего: кромка обязана быть
 * продолжением той же кожи, иначе на грани видно стык.
 */
export const COVER_EDGE_COLOR = 0x201a10;

/** Торец бумажного блока: та же бумага, что и страница, чуть темнее. */
export const PAPER_COLOR = '#d8d0bb';

/**
 * Линии между листами на торце блока.
 *
 * Не чёрные и не серые: срез бумаги затенён самой бумагой, и тень в нём тёплая.
 * Холодный серый читался бы металлом, а не стопкой листов.
 */
export const SHEET_INK = '#a2967c';

/**
 * Убранная поза: закрытая книга в правом нижнем углу кадра.
 *
 * Дистанция считается, а не подбирается на глаз. При вертикальном угле обзора
 * 65° видимая высота на расстоянии d равна 2·d·tan(32.5°) = 1.274·d. Чтобы
 * страница высотой 0.28 заняла около четверти кадра, нужно d ≈ 0.9.
 *
 * Угол правый нижний: сверху висит кнопка «Меню», внизу по центру — дорожка
 * глав, слева внизу — компас. Правый низ у мира свободен.
 *
 * Смещение здесь — только ориентир на первый кадр: место в углу считает
 * `stowedCorner` по фактическим пропорциям окна, иначе на широком мониторе
 * книга висела бы посреди пустоты вместо угла. Начиная с первой протяжки место
 * держит посетитель, и угол ему больше не навязывается.
 *
 * Поворота здесь нет: убранный том разворачивается лицом к глазу — обложка
 * встаёт поперёк луча зрения, а не параллельно плоскости кадра. Разница видна
 * именно в углу: у книги есть толщина, и параллельная кадру обложка показывала
 * там боковую грань — том читался приоткрытой дверцей, а не лежащей книгой.
 */
export const STOWED = {
  position: new THREE.Vector3(0.6, -0.34, -0.9),
};

/**
 * Отступ убранной книги от нижней кромки кадра, пикселей.
 *
 * Считается до середины тома — с поправкой на то, что начало координат книги
 * стоит у корешка (см. `closedMiddle`), а не до её нижнего края.
 * В пикселях, а не в юнитах: книга встаёт над нижним рядом кнопок оболочки, а
 * тот свёрстан в пикселях и от пропорций окна не зависит. Отступ в юнитах на
 * низком окне подпускал бы книгу под кнопки, а на высоком отодвигал бы её к
 * середине кадра.
 *
 * Полторы сотни — это ряд кнопок, половина книги и зазор над рядом: замер по
 * кадру 1400×900 дал у книги низ на 839 пикселях при верхе кнопки на 853.
 */
export const STOWED_GAP = 169;

/**
 * Отступ убранной книги от правой кромки кадра, пикселей.
 *
 * Тоже до середины тома. Столько, сколько от правой кромки до середины кнопки
 * в правом нижнем углу, плюс поправка на разворот: книга смотрит лицом к глазу,
 * и в углу кадра её силуэт уходит от середины габарита на пару десятков
 * пикселей. Замер по кадру 1400×900: середина книги и середина кнопки сходятся
 * на 1294 пикселях.
 */
export const STOWED_SIDE = 125;

/**
 * Размер убранного тома против его натуральной величины.
 *
 * Три четверти: в углу книга — метка, а не предмет разговора, и в натуральную
 * величину она отъедала у мира заметный кусок кадра. Меньше двух третей по ней
 * становится трудно попасть указателем — а щелчок по тому и есть единственный
 * способ его открыть.
 */
export const STOWED_SCALE = 0.75;

/**
 * Размер раскрытой книги против натуральной величины.
 *
 * На пятую часть крупнее: раскрытый разворот — это текст, который читают, и
 * лишняя пятая часть кегля решает, читается он с одного взгляда или с
 * прищуром.
 */
export const READING_SCALE = 1.2;

/**
 * Длительности переходов, в секундах.
 *
 * Переворот втрое длиннее раскрытия не для красоты: за 0.7 с дуга листа
 * проходила мимо глаза, и переворот читался подменой картинки. Страница живой
 * книги идёт около секунды с четвертью.
 */
export const OPEN_SECONDS = 0.8;
export const FLIP_SECONDS = 1.25;

/**
 * Сколько идёт пролистывание пачкой — дорога до заложенной страницы целиком.
 *
 * Закладка ведёт на второй разворот, а листают к ней и с двадцатого: честные
 * перевороты по секунде с четвертью дали бы полминуты ожидания. Поэтому вся
 * дорога укладывается в полтора вздоха, а длительность одного переворота
 * делится на их число.
 *
 * Мгновенная подмена разворота была бы дешевле, но она врёт: книга — предмет,
 * и путь до заложенной страницы виден в ней руками. Собственно ради этого
 * зрелища закладку и держат.
 */
export const RIFFLE_SECONDS = 1.6;

/**
 * Короче этого один переворот в пачке не идёт.
 *
 * При шестидесяти кадрах в секунду девять сотых — это пять кадров: меньше, и
 * лист не успевает показать дугу, пачка вырождается в мельтешение текстур.
 */
export const RIFFLE_MIN = 0.09;

/**
 * Во сколько раз последний переворот пачки длиннее прочих.
 *
 * Стопка листов летит быстро, а последняя страница укладывается — так книга и
 * останавливается на нужном месте. Без замедления пачка обрывается стуком.
 */
export const RIFFLE_SETTLE = 2.5;

/**
 * Сколько книга едет из угла кадра в позу чтения, не раскрываясь.
 *
 * Перенос отделён от раскрытия намеренно: книга лежит в углу закрытой, и
 * обложка — часть кадра, а не заставка. Сначала том подъезжает целиком, и
 * только потом расходятся крышки.
 */
export const CARRY_SECONDS = 0.7;

/**
 * Пауза между приездом и раскрытием.
 *
 * Ровно та доля секунды, за которую глаз успевает прочитать обложку. Без неё
 * крышки начинают расходиться на ходу, и рисунок проходит мимо.
 */
export const COVER_HOLD = 0.5;

/**
 * Во сколько раз короче идут переходы при просьбе о покое.
 *
 * Не ноль: в этом проекте `reduced` — про амплитуду, а не про отсутствие
 * движения (мир при нём поднимается, см. `capability.ts`). Мгновенная подмена
 * разворота была бы резче полноценной анимации, а не мягче.
 */
export const CALM_FACTOR = 0.3;

/** Короче этого переход перестаёт читаться и становится скачком. */
export const CALM_FLOOR = 0.12;
