/**
 * Математика листающегося листа: привязка вершин к костям и углы костей.
 *
 * Файл намеренно не знает про `three`. Всё, что здесь есть, — числа, и это
 * единственная часть книги, которую можно проверить тестом без браузера и без
 * видеокарты. Остальное — сборка мешей и материалов — проверяется глазами.
 *
 * Почему кости, а не вершинный шейдер: чужие проходы содержат чанки скиннинга
 * и потому видят согнутый лист, а собственный шейдер они бы не увидели —
 * глубина легла бы по плоской странице. Довод про `GTAOPass` с тех пор отпал:
 * книга уехала в свою сцену и в этот проход не попадает. Остался главный —
 * `SkinnedMesh.getVertexPosition` применяет кости при рейкасте, и на этом
 * живут ссылки на странице.
 */

/** Костей в цепочке листа. Восьми хватает на дугу без огранки. */
export const BONES = 8;

/** Делений плоскости вдоль листа. Вершин выходит `(SEGMENTS + 1) * 2`. */
export const SEGMENTS = 20;

/**
 * Насколько лист выгибается дугой в середине переворота, от 0 до 1.
 *
 * Единица — весь поворот роздан по цепочке поровну, то есть лист в середине
 * переворота согнут ровной дугой. Ноль — лист остаётся плоской пластиной на
 * шарнире у корешка.
 *
 * Меньше единицы брать незачем: именно ради этой дуги всё и делается.
 */
const BOW = 1;

/** Привязка одной вершины: две кости и их доли. Доли всегда дают в сумме 1. */
export type VertexBinding = {
  index: [number, number];
  weight: [number, number];
};

/**
 * К каким костям привязана вершина с координатой `x`.
 *
 * Начало отсчёта — корешок, левый край листа (`x = -width / 2`). Кости стоят
 * равномерно от корешка к внешнему краю, вершина делится между своей костью и
 * следующей пропорционально тому, где она стоит между ними.
 *
 * @param x координата вершины вдоль листа, в локальных единицах меша
 * @param width ширина листа
 * @param bones длина цепочки костей
 */
export function vertexBinding(x: number, width: number, bones: number): VertexBinding {
  if (bones <= 1) return { index: [0, 0], weight: [1, 0] };

  const step = width / bones;
  const along = (x + width / 2) / step;

  // Вершины на самом краю дают `along === bones` — за последнюю кость выходить
  // некуда, поэтому хвост целиком её.
  const slot = Math.floor(along);
  if (slot >= bones - 1) return { index: [bones - 1, bones - 1], weight: [1, 0] };
  if (slot < 0) return { index: [0, 0], weight: [1, 0] };

  const fraction = along - slot;
  return { index: [slot, slot + 1], weight: [1 - fraction, fraction] };
}

/** Готовые атрибуты скиннинга: по четыре числа на вершину, как ждёт three. */
export type PageSkin = {
  index: Uint16Array;
  weight: Float32Array;
};

/**
 * Строит атрибуты `skinIndex` и `skinWeight` для плоскости листа.
 *
 * Берёт сырой массив позиций, а не `BufferAttribute`, чтобы остаться
 * проверяемым без `three`.
 *
 * @param positions позиции вершин подряд: x, y, z, x, y, z…
 * @param width ширина листа
 * @param bones длина цепочки костей
 */
export function pageSkin(
  positions: ArrayLike<number>,
  width: number,
  bones: number,
): PageSkin {
  const count = Math.floor(positions.length / 3);
  const index = new Uint16Array(count * 4);
  const weight = new Float32Array(count * 4);

  for (let vertex = 0; vertex < count; vertex++) {
    const binding = vertexBinding(positions[vertex * 3] ?? 0, width, bones);

    index[vertex * 4] = binding.index[0];
    index[vertex * 4 + 1] = binding.index[1];
    weight[vertex * 4] = binding.weight[0];
    weight[vertex * 4 + 1] = binding.weight[1];
  }

  return { index, weight };
}

/**
 * Углы костей на заданной доле переворота.
 *
 * Каждое число — поворот кости **относительно родителя**, в радианах. Сумма
 * всей цепочки — угол, на который повёрнут лист целиком: от нуля лёжа справа
 * до −π лёжа слева.
 *
 * Знак отрицательный, и это не вкусовщина. Лист лежит в плоскости XY нормалью
 * на камеру, корешок по оси Y. Поворот вокруг +Y переводит точку `(x, 0)` в
 * `(x·cosθ, −x·sinθ)`: при положительном θ свободный край уходит в −Z, то есть
 * **внутрь книги**, за переплёт и бумажный блок. Лист при этом честно
 * анимируется, но всю середину переворота его не видно — читается как мгновенная
 * подмена разворота. При отрицательном θ край поднимается к зрителю, как у
 * настоящей страницы, и переворот виден целиком.
 *
 * Поворот раскладывается по цепочке **по-разному в зависимости от доли**, и в
 * этом вся суть.
 *
 * На концах он весь сидит на первой кости — шарнире у корешка. Иначе лист не
 * лёг бы в стопку: кости сдвинуты друг от друга вдоль бумаги, и равномерный
 * поворот сворачивает цепочку в дугу. При сумме π это полукольцо радиусом
 * `ширина/π`, свободный край уходит на два радиуса вбок, и лист застывает
 * скрученной трубкой поперёк книги — замер на ширине 0.2 давал торчащие 0.12.
 *
 * В середине переворота он, наоборот, роздан поровну — и лист выгибается
 * ровной дугой. Без этого он остаётся плоской пластиной и на половине пути
 * встаёт к камере **ребром**: плоскость нулевой толщины с ребра невидима, и
 * сквозь неё видно мир за книгой. Дуга держит бумагу повёрнутой к зрителю всю
 * дорогу — ровно то, за счёт чего переворот виден и у настоящей книги.
 *
 * Переход между двумя раскладами — синус доли: ноль на обоих концах, единица
 * посередине. Сумма цепочки при любой доле остаётся ровно `turn`, поэтому
 * общий угол выгиб не трогает.
 *
 * @param progress доля переворота от 0 до 1
 * @param bones длина цепочки костей
 */
export function flipRotations(progress: number, bones: number): number[] {
  if (bones <= 0) return [];

  const clamped = Math.min(Math.max(progress, 0), 1);
  const turn = -Math.PI * clamped;

  if (bones === 1) return [turn];

  const bow = BOW * Math.sin(Math.PI * clamped);
  const share = turn / bones;
  const rotations: number[] = [];

  for (let bone = 0; bone < bones; bone++) {
    // Шарнир отдаёт цепочке ровно столько, сколько она забирает: сумма всегда
    // равна `turn`, как ни выгибай.
    rotations.push(bone === 0 ? turn - bow * (turn - share) : bow * share);
  }

  return rotations;
}
