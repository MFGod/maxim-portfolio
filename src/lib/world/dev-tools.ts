/**
 * Выключатель инструментов подбора.
 *
 * Подбор ракурсов, номера над инстансами и схема пути нужны, пока мир
 * настраивают, и мешают, когда его смотрят. Держать их закомментированными
 * нельзя: закомментированный код не проверяется ни типами, ни линтером, ни
 * тестами — через месяц он перестаёт собираться, и это выясняется ровно в тот
 * момент, когда инструмент понадобился.
 *
 * Поэтому код живёт обычной жизнью, а показывается по флагу. Включить:
 * поставить `true` и перезапустить `next dev`. В сборку ничего не попадёт —
 * условие статическое, и всё за ним отсекается вместе с `NODE_ENV`.
 *
 * Что включается:
 * - панель «Запомнить ракурс · Скопировать · Очистить» в углу мира;
 * - горячие клавиши Shift+S (снимок) и Shift+E (выгрузка в буфер);
 * - карманы оболочки от несохранённых снимков — чтобы подобранный кадр
 *   не выталкивало куполом ещё до переноса в данные.
 *
 * Остальное — `window.__world.marks`, `shell`, `shots` — доступно в консоли
 * всегда при `next dev` и флагом не управляется: оно ничего не рисует само.
 */
export const SHOT_TOOLS = false;

/**
 * Расстановка фигур: панель в углу, постановка щелчком по земле, перетаскивание
 * и выгрузка в `src/data/world-figures.ts`. Включена, пока расстановки нет —
 * гасить её надо тем же способом, что и подбор ракурсов, когда мир населён.
 */
export const FIGURE_TOOLS = true;

/** Инструменты живут только в разработке, флаг лишь добавляет условие. */
export const shotToolsEnabled = (): boolean =>
  process.env.NODE_ENV === 'development' && SHOT_TOOLS;

export const figureToolsEnabled = (): boolean =>
  process.env.NODE_ENV === 'development' && FIGURE_TOOLS;
