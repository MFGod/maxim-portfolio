/**
 * Что делает мир, когда его перестали трогать.
 *
 * Две ступени, а не одна. Через двадцать секунд камера начинает медленно
 * поводить взглядом: посетитель отвлёкся на секунду, и мир не должен ни
 * замирать картинкой, ни срываться в ролик — достаточно, чтобы кадр дышал.
 * Через минуту с четвертью становится ясно, что за экраном никого, и мир
 * уходит в облёт: это уже хранитель экрана, и он вправе забрать камеру.
 *
 * Правила здесь, а не в сцене, по той же причине, что и у `route.ts`: пороги
 * и разгон проверяются числами. Ошибка в них выглядит как «камера дёргается
 * сама» или «ролик включается посреди чтения» — то, что ловится глазами за
 * минуту ожидания на каждую проверку.
 */

/** Через сколько секунд покоя камера начинает поводить взглядом. */
export const DRIFT_AFTER = 20;

/** Через сколько секунд покоя мир уходит в облёт. */
export const REST_AFTER = 75;

/**
 * За сколько секунд поворот набирает полную скорость.
 *
 * Без разгона взгляд трогается рывком ровно на двадцатой секунде — и это
 * читается сбоем, а не движением.
 */
export const DRIFT_EASE = 4;

/** Полная скорость поворота, радиан в секунду. Примерно градус. */
export const DRIFT_SPEED = 0.018;

/** Что мир делает сейчас. */
export type IdlePhase = 'active' | 'drift' | 'rest';

export function idlePhase(idle: number): IdlePhase {
  if (idle >= REST_AFTER) return 'rest';
  if (idle >= DRIFT_AFTER) return 'drift';

  return 'active';
}

/**
 * Насколько повернуть взгляд за этот кадр, в радианах.
 *
 * Ноль до порога и на облёте: облётом камеру ведёт риг, и второй хозяин у неё
 * в этот момент лишний.
 */
export function driftYaw(idle: number, delta: number): number {
  if (idle < DRIFT_AFTER || idle >= REST_AFTER) return 0;

  const share = Math.min((idle - DRIFT_AFTER) / DRIFT_EASE, 1);
  return DRIFT_SPEED * share * delta;
}
