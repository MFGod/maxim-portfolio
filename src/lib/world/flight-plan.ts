/**
 * Планирование перелёта: как обойти то, что стоит на пути.
 *
 * Прямая между двумя станциями почти всегда во что-нибудь упирается — замер по
 * маршруту дал задевание на всех двадцати одном участке: кроны, руины, скалы,
 * Божественная башня, а местами и сам рельеф. Двигать станции нельзя, их
 * подбирали вживую по кадру. Значит гнуть надо путь между ними.
 *
 * Гнуть именно **дугой**. Раньше над препятствием ставилось плато: опора на
 * входе, опора на выходе, обе на одной высоте. Камера въезжала в него углом, и
 * замер это подтверждал — над башней радиус поворота падал до 0.05 юнита при
 * ускорении в 2461 юнит в секунду за секунду. Это и видно как рывок.
 *
 * Теперь опоры стоят равномерно по пути — равномерный шаг это то, на чём
 * кривая работает лучше всего, — а высота каждой считается в три приёма:
 *
 * 1. **Луч** вдоль прямой говорит, где и на сколько не хватает зазора.
 * 2. **Дилатация**: опора берёт наибольшее требование в своей зоне влияния —
 *    шаг до соседней. Иначе кривая между опорами срезает угол и входит в
 *    препятствие, начавшееся сразу за опорой.
 * 3. **Юбка и бугор**: соседняя с дугой опора забирает часть подъёма, а
 *    вершина приподнимается — из полки с обрывами получается дуга.
 *
 * После перехода на тех же пробах: радиус 3.3 вместо 0.05, ускорение 150
 * вместо 2461. Зазор при этом только растёт — все три приёма опоры поднимают,
 * а не опускают.
 *
 * Модуль чистый: карта высот приходит функцией, поэтому план проверяется
 * тестом без сцены и без браузера.
 */

import { samplePath, type PathKey, type Point3 } from './camera-path';

/** Высота всего, что мешает, в точке: рельеф, оболочка, объекты. */
export type CeilingProbe = (x: number, z: number) => number | null;

/** На сколько камера проходит выше препятствия. */
const CLEARANCE = 0.8;

/** Сколько точек проверяем вдоль отрезка. */
const SAMPLES = 60;

/**
 * Сколько юнитов у концов пути подъём не применяется.
 *
 * Станции стоят вплотную к тому, что показывают: у благодати под деревьями, у
 * стены замка. Требовать зазора и там значит взмывать над кроной сразу после
 * старта и падать перед прибытием — камера дёргалась бы на каждом шаге.
 *
 * Считается в юнитах, а не в долях пути. Доля растёт вместе с перелётом: на
 * шестидесяти юнитах прежние 0.18 ослепляли планировщик на одиннадцать юнитов
 * у каждого конца — и оба замеренных рывка сидели ровно на границе этой слепой
 * зоны, на долях 0.20 и 0.87. Камера входила в скалу, которую план не искал.
 */
const EDGE_UNITS = 1.6;

/** Больше прежней доли слепая зона не станет: на коротких шагах она и была права. */
const EDGE_MAX = 0.18;

/** Ниже этого подъём не стоит опоры: дуга пройдёт и так. */
const MIN_LIFT = 0.25;

/** Бугор в вершине, доля подъёма: дуга, а не полка. */
const APEX = 0.14;

/**
 * Юбка: доля подъёма, которую забирает соседняя с дугой опора.
 *
 * Без неё вся высота набирается за один шаг между опорами, и на въезде кривая
 * закладывает вираж: на одиноком шпиле радиус поворота падал до 1.67 юнита.
 * Юбка растягивает набор на два шага и поднимает радиус до 2.9.
 */
const SKIRT = 0.45;

/** Сколько опор ставится между станциями, когда путь гнётся. */
const INNER_KEYS = 6;

const lerp = (a: number, b: number, t: number): number => a + (b - a) * t;

const lerpPoint = (a: Point3, b: Point3, t: number): Point3 => [
  lerp(a[0], b[0], t),
  lerp(a[1], b[1], t),
  lerp(a[2], b[2], t),
];

/**
 * Луч вдоль прямой: на какой высоте камере разрешено идти в каждой выборке.
 *
 * Высота абсолютная, а не подъём над прямой. Разница видна на наклонном
 * перелёте: подъём, посчитанный там, где прямая ниже, прикладывается к опоре,
 * где она уже выше, — и зазор теряется. Замер по перелёту на восток: у скалы
 * оставалось 0.17 юнита вместо положенных 0.8, купол дотягивал остальное
 * рывком в 343 юнита в секунду за секунду.
 */
function probeCeilings(
  from: PathKey,
  to: PathKey,
  ceiling: CeilingProbe,
  edge: number,
): number[] {
  const needs: number[] = [];

  for (let step = 0; step <= SAMPLES; step++) {
    const t = step / SAMPLES;
    const inside = t >= edge && t <= 1 - edge;

    const point = lerpPoint(from.at, to.at, t);
    const top = inside ? ceiling(point[0], point[2]) : null;

    needs.push(top === null ? -Infinity : top + CLEARANCE);
  }

  return needs;
}

/**
 * Подъём опоры: наибольшее требование в её зоне влияния.
 *
 * Зона — шаг до соседней опоры. Иначе кривая между двумя опорами срезает угол
 * и входит в препятствие, которое началось сразу за опорой: замер давал провал
 * на 0.73 юнита внутрь холма. Так каждая точка пути зажата между опорами,
 * которые её препятствие уже перекрыли.
 */
function keyLift(needs: number[], t: number, reach: number, floor: number): number {
  const first = Math.max(0, Math.ceil((t - reach) * SAMPLES));
  const last = Math.min(SAMPLES, Math.floor((t + reach) * SAMPLES));

  let top = -Infinity;
  for (let index = first; index <= last; index++) {
    if (needs[index]! > top) top = needs[index]!;
  }

  const lift = top - floor;
  return lift < MIN_LIFT ? 0 : lift;
}

/**
 * Бугор поверх ровного участка подъёма.
 *
 * Без него камера идёт над препятствием полкой — ровно, но с изломом на входе
 * и выходе. Бугор считается по положению опоры внутри непрерывного участка
 * подъёма: в середине выше, к краям сходит на нет.
 */
function bulge(lifts: number[], index: number): number {
  let first = index;
  while (first > 0 && lifts[first - 1]! > 0) first--;

  let last = index;
  while (last < lifts.length - 1 && lifts[last + 1]! > 0) last++;

  if (first === last) return 0;

  const middle = (first + last) / 2;
  const half = (last - first) / 2 + 1;

  return APEX * Math.cos((Math.PI / 2) * ((index - middle) / half)) ** 2;
}

/**
 * Окно у станций: подъём гасится к концам пути.
 *
 * Зона влияния опоры дотягивается почти до станции, а взмывать сразу после
 * старта камере нельзя. К доле `edge` окно уже полностью открыто, а препятствия
 * ближе неё и не ищутся — требуемый зазор окно не срезает.
 */
function edgeWindow(t: number, edge: number): number {
  const away = Math.min(t, 1 - t);
  if (away >= edge) return 1;

  return 0.5 * (1 - Math.cos(Math.PI * (away / edge)));
}

/**
 * Строит путь от станции к станции, обходя препятствия по дуге.
 *
 * @param from откуда камера летит — обычно её текущее положение
 * @param to куда: утверждённый ракурс, его трогать нельзя
 * @param ceiling высота препятствий; `null` там, где ничего нет
 * @returns опоры пути, включая концы. Без препятствий — просто `[from, to]`
 */
export function planFlight(
  from: PathKey,
  to: PathKey,
  ceiling: CeilingProbe,
): PathKey[] {
  const span = Math.hypot(
    to.at[0] - from.at[0],
    to.at[1] - from.at[1],
    to.at[2] - from.at[2],
  );
  const edge = span > 0 ? Math.min(EDGE_MAX, EDGE_UNITS / span) : EDGE_MAX;

  const probed = probeCeilings(from, to, ceiling, edge);
  const reach = 1 / (INNER_KEYS + 1);

  const raw = Array.from({ length: INNER_KEYS }, (_, index) => {
    const t = (index + 1) * reach;
    return keyLift(probed, t, reach, lerp(from.at[1], to.at[1], t));
  });

  if (raw.every((lift) => lift === 0)) return [from, to];

  // Юбка только поднимает опоры, поэтому зазор, добытый дилатацией, цел.
  const lifts = raw.map((lift, index) =>
    Math.max(lift, SKIRT * Math.max(raw[index - 1] ?? 0, raw[index + 1] ?? 0)),
  );

  /*
   * Прямой перелёт без обхода — по нему считается взгляд.
   *
   * Опоре нельзя ставить взглядом точку с прямой между концами: кривая ведёт
   * **направление**, и поднятая опора, смотрящая в такую точку, задаёт
   * направление, которого на гладкой угловой траектории нет. Замер: на трёх
   * перелётах план втрое поднимал угловую скорость (до 247°/с против 87) и в
   * двадцать раз — угловое ускорение.
   *
   * Поэтому направление и дальность берутся у того же перелёта без обхода, а
   * прикладываются от поднятой точки. Подъём тогда и вправду меняет только
   * высоту камеры, а не то, куда она смотрит.
   */
  const chord: PathKey[] = [from, to];

  const raised: Point3[] = lifts.map((lift, index) => {
    const t = (index + 1) * reach;
    const flat = lerpPoint(from.at, to.at, t);

    return [flat[0], flat[1] + lift * (1 + bulge(lifts, index)) * edgeWindow(t, edge), flat[2]];
  });

  /*
   * Доля пути, а не доля прямой.
   *
   * Обход удлиняет путь неравномерно: там, где камера лезет вверх, она проходит
   * больше, чем показывает доля `t`. Если взять взгляд по доле прямой, поворот
   * сожмётся в те участки, где дуги нет. Замер это и показал: без плана кадр
   * разворачивался ровным колоколом (10-34-59-78-87-87-80-61-35-10 °/с), с
   * планом — почти стоял и потом швырял на 195.
   */
  const points: Point3[] = [from.at, ...raised, to.at];
  const marks = [0];
  for (let index = 1; index < points.length; index++) {
    marks.push(
      marks[index - 1]! +
        Math.hypot(
          points[index]![0] - points[index - 1]![0],
          points[index]![1] - points[index - 1]![1],
          points[index]![2] - points[index - 1]![2],
        ),
    );
  }
  const length = marks.at(-1)!;

  const inner = raised.map((at, index) => {
    const along = length === 0 ? 0 : marks[index + 1]! / length;
    const aimed = samplePath(chord, along);

    return {
      at,
      look: [
        at[0] + (aimed.look[0] - aimed.position[0]),
        at[1] + (aimed.look[1] - aimed.position[1]),
        at[2] + (aimed.look[2] - aimed.position[2]),
      ] as Point3,
    };
  });

  return [from, ...inner, to];
}
