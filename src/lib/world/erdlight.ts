/**
 * Золото Эрдтри: свет, который крона отдаёт земле.
 *
 * Свечение у крон было и раньше — эмиссия `#ffa51d` плюс `UnrealBloomPass`, —
 * но светилась только сама крона. Трава под деревом оставалась ровно такой же,
 * как в чистом поле в двух сотнях юнитов оттуда, и дерево читалось нарисованным
 * на небе, а не стоящим в мире. Настоящий источник кладёт под крону пятно,
 * и золото начинает исходить от дерева, а не лежать на нём.
 *
 * Источников три, а не по одному на дерево. Свет в трёх измерениях здесь
 * считается прямым проходом: каждый источник входит в шейдер каждого материала
 * карты, и дюжина — это пересборка всех программ и дюжина витков цикла на
 * каждый пиксель одиннадцати миллионов треугольников. Три ближайших к зрителю
 * дерева дают тот же ответ на вопрос «откуда золото»: дальше по карте пятно под
 * кроной всё равно уходит в подпиксель, и за него отвечает ореол.
 *
 * Сила идёт за размером кроны: мелкий Эрдтри у дороги и главное дерево мира не
 * могут отдавать земле поровну. Множитель — в `erdlightPower`.
 *
 * Число источников постоянно на всю жизнь сцены. Заводить и гасить их по ходу
 * значило бы пересобирать шейдеры карты посреди прогулки — отсюда пара из
 * `seed` (деревья пришли) и `update` (кому из них светить сейчас).
 *
 * Тени источники не отбрасывают: тень в кадре идёт от лунного ключевого света,
 * и вторая, снизу от кроны, спорила бы с ней направлением.
 */

import * as THREE from 'three';

/** Цвет — тот же, что эмиссия кроны и свечение листьев: золото у мира одно. */
export const ERDLIGHT_COLOR = 0xffa51d;

/**
 * Источников в пуле.
 *
 * Три — потолок, а не вкус: замер кадра до правки дал 588 вызовов и 11.4 млн
 * треугольников при трёх источниках сцены (ambient, ключевой, полусфера).
 * Каждый новый точечный источник — это виток на пиксель по всей этой площади.
 * Три ближайших дерева закрывают то, ради чего всё затевалось: дерево рядом со
 * зрителем светит на землю.
 *
 * Замер GPU-таймером (`EXT_disjoint_timer_query_webgl2`) 2026-08-28, тот же
 * кадр на входе в мир: 47.85 мс с источниками против 47.77 мс без них. Разница
 * тонет в разбросе между прогонами (десятки мс), то есть три источника кадру не
 * стоят ничего различимого. Дюжина так не проверялась — там начинается
 * пересборка программ, а не витки цикла.
 */
export const ERDLIGHT_COUNT = 3;

/**
 * Досягаемость источника у обычного дерева, юнитов.
 *
 * Кроны стоят на высоте 4–20 юнитов, значит до земли под собой источнику надо
 * два десятка. Дальше свет всё равно съеден затуханием (`decay: 2`), а предел
 * отсекает от расчёта геометрию, до которой золото не доходит. У крупных крон
 * предел растёт — см. `erdlightReach`.
 */
export const ERDLIGHT_REACH = 26;

/**
 * Сила источника у обычного дерева, кандел, при полном наборе освещения.
 *
 * Подобрано вживую 2026-08-28 на входе в мир, сравнением одного и того же
 * кадра. Первая прикидка была 260, и в сумерках (множитель 1.15) это дало
 * триста кандел: тёплыми становились не только трава и кроны рядом, но и
 * серый камень руин через полкарты — мир переставал быть каменным. На ста
 * золото доходит до травы под деревом и до ближних крон, а руины остаются
 * камнем.
 *
 * Число крупное не от щедрости: при `decay: 2` сила падает как квадрат
 * расстояния, и до земли в десяти юнитах от кроны доходит сотая доля.
 */
export const ERDLIGHT_INTENSITY = 100;

/**
 * Радиус кроны, которую считаем обычным деревом, юнитов.
 *
 * Замер по живой карте 2026-08-28 (`treesOf`): девять деревьев, у восьми радиус
 * листвы 1.5–1.7, у обломанного на склоне — 0.8, у главного — 7.9. Полтора с
 * небольшим и есть рядовое дерево: на нём множитель силы равен единице, и
 * `ERDLIGHT_INTENSITY` читается как «сколько кандел у обычного дерева».
 */
export const ERDLIGHT_TYPICAL_RADIUS = 1.6;

/**
 * Во сколько раз слабее обычного светит самое мелкое дерево.
 *
 * Не ноль: у мелкой кроны свет должен быть слабым, а не отсутствующим — иначе
 * половина деревьев снова читается нарисованной на небе. Порог задевает только
 * обломанные кроны вроде той, что на склоне: до трети силы падает всё, что
 * уже половины рядового дерева.
 */
export const ERDLIGHT_MIN_POWER = 0.3;

/**
 * Во сколько раз ярче обычного светит самое крупное.
 *
 * Потолок нужен: сила идёт за площадью кроны, а у главного дерева радиус впятеро
 * больше рядового — квадрат дал бы двадцатипятикратное золото, и оно залило бы
 * полкарты. Вчетверо — предел, на котором главное дерево читается главным, а
 * камень руин остаётся камнем.
 */
export const ERDLIGHT_MAX_POWER = 4;

/**
 * До какого расстояния до зрителя дерево светит в полную силу, юнитов.
 */
export const ERDLIGHT_FULL = 42;

/**
 * За каким расстоянием дерево гаснет совсем, юнитов.
 *
 * Это не физика, а честная плата за пул из трёх: у дальнего дерева свет
 * отбирают в пользу ближнего, и отбирать надо там, где отбор не виден. За
 * восемь десятков юнитов пятно под кроной — это единицы пикселей, и его уход
 * заметить нельзя. Ближе — можно, поэтому между `FULL` и `DROP` источник
 * гаснет плавно, а не щёлкает.
 */
export const ERDLIGHT_DROP = 82;

/** Скорость разгорания и угасания, долей силы в секунду. */
export const ERDLIGHT_FADE = 1.6;

/**
 * Как часто пересматривается, каким деревьям светить, секунд.
 *
 * Не каждый кадр: перебор дюжины деревьев дешёвый, но бессмысленный — зритель
 * за шестую долю секунды не проходит и юнита, а набор ближайших меняется куда
 * реже.
 */
export const ERDLIGHT_REBIND = 0.25;

/**
 * Дерево, которому есть чем светить.
 *
 * Свой тип, а не `Tree` из `leaves.ts`: пулу источников нужны только место и
 * размер кроны, и на этих двух полях он проверяется без карты и без меша.
 */
export type ErdlightTree = {
  /** Середина листвы в мировых координатах. */
  position: THREE.Vector3;
  /** Половина горизонтального габарита листвы, юнитов. */
  radius: number;
};

/**
 * Множитель силы источника по размеру кроны.
 *
 * Квадрат отношения радиусов, а не само отношение: светит площадь листвы, а
 * растёт она как квадрат. Пока все источники стояли на одной силе, мелкий
 * Эрдтри у дороги отдавал земле столько же золота, сколько главное дерево
 * мира, — это было первым, что бросалось в глаза.
 *
 * @param radius половина горизонтального габарита кроны, юнитов
 */
export function erdlightPower(radius: number): number {
  const share = (radius / ERDLIGHT_TYPICAL_RADIUS) ** 2;

  return Math.min(ERDLIGHT_MAX_POWER, Math.max(ERDLIGHT_MIN_POWER, share));
}

/**
 * Досягаемость источника по размеру кроны, юнитов.
 *
 * Корень из множителя силы, а не сам множитель: предел — это расстояние, за
 * которым свет съеден затуханием, а оно идёт как квадрат. Так круг света растёт
 * вместе с деревом, но у главного не выходит за половину карты.
 *
 * @param radius половина горизонтального габарита кроны, юнитов
 */
export function erdlightReach(radius: number): number {
  return ERDLIGHT_REACH * Math.sqrt(erdlightPower(radius));
}

/**
 * Доля силы источника на этом расстоянии до зрителя.
 *
 * Пороги растут вместе с кроной тем же множителем, что и досягаемость: пятно
 * под главным деревом вчетверо ярче и вдвое шире, и гаснуть оно должно вдвое
 * дальше, чем у рядового. Иначе доминанта кадра тухнет там же, где куст.
 *
 * @param distance расстояние от камеры до кроны, юнитов
 * @param radius половина горизонтального габарита кроны, юнитов
 * @returns от 1 вблизи до 0 за пределом видимости пятна
 */
export function erdlightFalloff(distance: number, radius: number): number {
  const spread = Math.sqrt(erdlightPower(radius));
  const full = ERDLIGHT_FULL * spread;
  const drop = ERDLIGHT_DROP * spread;

  if (distance <= full) return 1;
  if (distance >= drop) return 0;

  return 1 - (distance - full) / (drop - full);
}

/**
 * Насколько заметным будет пятно этого дерева с этого места.
 *
 * Сила, делённая на квадрат расстояния, — то же, чем глаз меряет яркость. Без
 * этого пул брал три ближайших дерева, и главное дерево мира оставалось тёмным
 * всякий раз, когда рядом с камерой оказывался куст: доминанта кадра проигрывала
 * мелочи под ногами, стоя вчетверо дальше.
 *
 * Единица в знаменателе держит вес конечным, когда камера стоит в самой кроне.
 *
 * @param radius половина горизонтального габарита кроны, юнитов
 * @param distance расстояние от камеры до кроны, юнитов
 */
export function erdlightWeight(radius: number, distance: number): number {
  return erdlightPower(radius) / (distance * distance + 1);
}

/**
 * Номера самых заметных отсюда деревьев.
 *
 * Разводить их не нужно: `treesOf` уже отдаёт по одному узлу на дерево, а не по
 * ячейке листвы.
 *
 * @param trees деревья карты
 * @param eye положение камеры
 * @param count сколько номеров нужно
 * @returns номера от заметного к незаметному; короче `count`, если деревьев меньше
 */
export function brightestTrees(
  trees: ErdlightTree[],
  eye: THREE.Vector3,
  count: number,
): number[] {
  return trees
    .map((tree, index) => ({
      index,
      weight: erdlightWeight(tree.radius, tree.position.distanceTo(eye)),
    }))
    .sort((a, b) => b.weight - a.weight)
    .slice(0, count)
    .map((entry) => entry.index);
}

/**
 * Подводит долю силы к цели за этот кадр.
 *
 * Отдельной функцией ради теста: именно здесь живёт обещание, что источник
 * разгорается и гаснет, а не щёлкает.
 *
 * @param level текущая доля
 * @param target доля, к которой идём
 * @param delta длительность кадра, секунд
 */
export function stepLevel(level: number, target: number, delta: number): number {
  const step = ERDLIGHT_FADE * delta;
  if (target > level) return Math.min(target, level + step);

  return Math.max(target, level - step);
}

/** Один источник пула и дерево, за которым он сейчас закреплён. */
type Lamp = {
  light: THREE.PointLight;
  /** Номер дерева в списке; `-1` — источник свободен и погашен. */
  tree: number;
  /** Доля силы: 0 — погашен, 1 — полная. */
  level: number;
};

export type Erdlight = {
  /**
   * Раздаёт источникам деревья. Зовётся один раз, когда карта пришла: до этого
   * светить не из чего.
   */
  seed: (trees: ErdlightTree[]) => void;
  /** Переставляет источники по ближайшим деревьям. Зовётся раз в кадр. */
  update: (camera: THREE.Camera, delta: number) => void;
  /**
   * Сила золота по времени суток. Ведёт тот же набор, что эмиссию крон:
   * в сумерках золото ярче, днём бледнее.
   */
  setLight: (value: number) => void;
  dispose: () => void;
};

/**
 * Заводит пул золотых источников.
 *
 * Источники создаются сразу и пустыми, до прихода карты: пересборка шейдеров
 * от нового источника стоит подвисания в полсекунды, и платить им лучше на
 * загрузке, а не посреди прогулки.
 *
 * @param parent сцена мира
 */
export function createErdlight(parent: THREE.Object3D): Erdlight {
  const lamps: Lamp[] = [];
  let trees: ErdlightTree[] = [];
  let wanted: number[] = [];
  let sinceRebind = ERDLIGHT_REBIND;
  let scale = 1;

  for (let index = 0; index < ERDLIGHT_COUNT; index++) {
    const light = new THREE.PointLight(
      ERDLIGHT_COLOR,
      0,
      ERDLIGHT_REACH,
      /* decay */ 2,
    );
    light.name = `world-erdlight-${index}`;
    light.castShadow = false;
    parent.add(light);
    lamps.push({ light, tree: -1, level: 0 });
  }

  const eye = new THREE.Vector3();

  return {
    seed: (value: ErdlightTree[]) => {
      trees = value;
      sinceRebind = ERDLIGHT_REBIND;
    },

    update: (camera: THREE.Camera, delta: number) => {
      if (trees.length === 0) return;

      camera.getWorldPosition(eye);

      sinceRebind += delta;
      if (sinceRebind >= ERDLIGHT_REBIND) {
        sinceRebind = 0;
        wanted = brightestTrees(trees, eye, lamps.length);
      }

      const taken = new Set(lamps.map((lamp) => lamp.tree));

      for (const lamp of lamps) {
        const keeps = lamp.tree >= 0 && wanted.includes(lamp.tree);

        /*
         * Смена дерева — только через ноль.
         *
         * Переставить погашенный источник ничего не стоит, а переставить
         * горящий значит погасить пятно в одном месте и зажечь в другом одним
         * кадром — тот самый щелчок, ради которого здесь весь этот учёт.
         */
        if (!keeps && lamp.level <= 0) {
          const free = wanted.find((index) => !taken.has(index));

          taken.delete(lamp.tree);
          lamp.tree = free ?? -1;
          taken.add(lamp.tree);
        }

        // Деревья на карте неподвижны, но ставить источник по своему дешевле,
        // чем помнить, в каком из ветвлений выше он сменил дерево.
        const tree = trees[lamp.tree];

        if (tree) {
          lamp.light.position.copy(tree.position);
          lamp.light.distance = erdlightReach(tree.radius);
        }

        const target =
          tree && wanted.includes(lamp.tree)
            ? erdlightFalloff(eye.distanceTo(tree.position), tree.radius)
            : 0;

        lamp.level = stepLevel(lamp.level, target, delta);
        lamp.light.intensity = tree
          ? ERDLIGHT_INTENSITY * erdlightPower(tree.radius) * lamp.level * scale
          : 0;
      }
    },

    setLight: (value: number) => {
      scale = value;
    },

    dispose: () => {
      for (const lamp of lamps) {
        lamp.light.dispose();
        lamp.light.removeFromParent();
      }
      lamps.length = 0;
      trees = [];
    },
  };
}
