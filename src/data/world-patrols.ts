/**
 * Дозоры: группы, идущие по дорогам мира.
 *
 * Маршруты сняты не на глаз. Направление проложено поиском по растру ленты
 * дорог (материал `Path`), а сама ломаная запечена инструментом
 * `__world.patrols` (`src/lib/world/dev-patrols.ts`) по геометрии этой ленты:
 * каждая точка сведена на её середину, высота взята у неё же.
 *
 * Так вышло потому, что первая укладка держалась дороги, но не её середины:
 * лента шириной 0,05–0,15 юнита уже самой фигуры, и половину пути идущий
 * свисал с неё ногой на траву. Замер по всей длине шагом 2 см: ступни вне
 * ленты на 37–62% пути, худшее провисание 0,146 юнита при росте фигуры 0,117.
 * Хуже того, у дозоров 3, 4 и 6 маршрут местами уходил под настил соседней
 * ленты — до 214 замеров подряд под дорогой, это и видно как проваливание.
 *
 * Причин было три, и все три сняты в `dev-patrols.ts`:
 *
 * 1. **Середина.** Точка сводится поперечным проходом по ленте: от места, где
 *    лента есть, в обе стороны, пока она не кончится. Проход ограничен 0,12
 *    юнита — иначе на перекрёстке «середина ленты» уезжает на середину
 *    перекрёстка.
 * 2. **Ярус.** Из ярусов ленты берётся верхний в пределах 0,15 от высоты
 *    предыдущего шага. Прежнее правило «ближайший к предыдущему» у съезда под
 *    мост цеплялось за нижнюю ленту и шаг за шагом уводило маршрут под настил.
 * 3. **Частота точек.** Ломаная упрощается по Дугласу—Пекеру с допуском 0,008
 *    по земле и 0,004 по высоте, а потом чинится по замеру ленты: где хорда
 *    срезает поворот или гребень, выброшенная точка возвращается.
 *
 * Куст на дороге маршрут обходит, не сходя с ленты: след инстансов берётся у
 * заселения (`dev-crowd.ts`), обход идёт от середины в обе стороны и потому
 * выходит наименьшим. Где лента занята целиком, идущий задевает листву — это
 * лучше, чем уйти на траву.
 *
 * Замер после перепекания: провисание 0,003 юнита (было 0,146), ступни вне
 * ленты 0–2,5% пути (было 37–62%), ни одного замера под чужим настилом,
 * касания — только кусты.
 *
 * Три дракона кружат над одним местом — воронкой Фарум Азулы, — но по разным
 * ярусам: виверна ниже всех (радиус 7, высота 8), обычный посередине (6 и 12),
 * старший обходит всё широко (10 и 16).
 *
 * Радиусы не произвольные: воронка в габарите 8,46 юнита, то есть полуширина
 * 4,2 — с радиусом 3 виверна летела прямо сквозь смерч. Между ярусами не
 * меньше четырёх юнитов по объёму, так что и между собой они не сходятся.
 *
 * Два дозора разнесены по карте: западный ходит вдоль дороги Лиурнии
 * (14,8 юнита), северный спускается с северо-востока на юг (22,3). Между ними
 * больше двадцати юнитов — встретиться они не могут.
 *
 * Восточная дорога Кейлида проверена и отвергнута: там лента идёт развалинами
 * в несколько ярусов и рвётся обрывами до восьми десятых юнита.
 */

export type WorldPatrol = {
  id: string;
  model: FigureModel;
  clip: FigureClip;
  /** Рост фигуры в юнитах мира. У местных жителей карты — 0,117. */
  height: number;
  /** Сколько идут цепочкой. */
  walkers: number;
  /** Промежуток между идущими, юниты. */
  spacing: number;
  /**
   * Юнитов в секунду.
   *
   * Не на глаз: клип `Walking_A` длится 1,067 с на цикл, а цикл ходьбы уносит
   * примерно 0,83 своего роста. При росте 0,117 это 0,09 юнита в секунду —
   * быстрее, и ноги начинают скользить по земле.
   */
  speed: number;
  /** Ломаная маршрута: X, Y, Z. Конец — разворот. */
  route: readonly (readonly [number, number, number])[];
};

